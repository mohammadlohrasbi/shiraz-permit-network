#!/bin/bash
# ---------------------------------------------------------------------------
# channel_contract_map.sh — نگاشت کانال ↔ قرارداد
# شبکه مدیریت و توکن‌سازی پروانه‌های ساختمانی شهرداری شیراز
#
# این فایل توسط network.sh و deploy-staged.sh منبع (source) می‌شود.
#
# ── چرا ۲ کانال و نه ۲۰ تا؟ ────────────────────────────────────────────────
# درسی که از پروژه 6G گرفتیم: تعداد زیاد قرارداد اسکلتی ارزش تحلیلی ندارد.
# اینجا محدودیت واقعی فابریک تعیین‌کننده است:
#
#   stub.InvokeChaincode(cc, args, channel) وقتی channel با کانال جاری
#   فرق داشته باشد فقط «خواندنی» است — نتیجه‌اش در read-set اعتبارسنجی
#   نمی‌شود و نوشتنش کامیت نمی‌گردد.
#
# قراردادهای پروانه، عوارض، توکن و خزانه باید در یک تراکنش اتمی با هم کار
# کنند (صدور پروانه = قفل توکن + ثبت بدهی + تغییر وضعیت). پس همه روی یک
# کانال اصلی می‌نشینند. جدایی حریم خصوصی با Private Data Collection انجام
# می‌شود، نه با کانال — که مکانیزم درست فابریک برای همین کار است.
#
# تنها چیزی که واقعاً مستقل است دفتر شفافیت است: آینه رویدادهای قطعی‌شده،
# که هیچ‌وقت لازم نیست در تراکنش اتمی با هسته باشد. جدا کردنش یک مزیت
# واقعی می‌دهد — می‌شود عضویت آن کانال را به شورای شهر، رسانه و دیوان
# محاسبات گسترش داد بی‌آنکه کسی به دفتر پروانه‌ها و داده مالکان برسد.
#
# نکته‌ای که موقع طراحی کشف شد: نسخه اول این پروژه چهار کانال داشت (بازار
# تراکم و استعلام هم جدا بودند). هر دو برگردانده شدند چون:
#   — معامله بازار باید انتقال توکن و ثبت درآمد را اتمی انجام دهد
#   — شرط عبور پرونده از مرحله استعلام باید در read-set اعتبارسنجی شود
# روی کانال جدا هیچ‌کدام تضمین نمی‌شد. جدایی سازمانی این دو با کنترل نقش
# داخل قرارداد و Private Data Collection تأمین می‌شود.
# ---------------------------------------------------------------------------

CHANNELS=(
  permitchannel      # هسته: مقررات، پلاک، پروانه، عوارض، توکن، خزانه، تخلف، بازار، استعلام
  auditchannel       # دفتر شفافیت عمومی و ردگیری درآمد
)

declare -A CHANNEL_CONTRACTS=(
  [permitchannel]="Regulation Parcel Permit Fee SqmToken Treasury Violation TdrMarket Inquiry"
  [auditchannel]="Audit"
)

# پروفایل configtx هر کانال. پیش‌فرض ApplicationChannel (هر ۸ سازمان).
# برای محدود کردن عضویت یک کانال، پروفایل مربوطه را در configtx.yaml
# (که از قبل تعریف شده) اینجا بگذارید و شبکه را از نو بسازید.
declare -A CHANNEL_PROFILE=(
  [permitchannel]="ApplicationChannel"
  [auditchannel]="ApplicationChannel"
)

# ---------------------------------------------------------------------------
# نگاشت سازمان فابریک ← واحد سازمانی شهرداری شیراز
# MSP ID ها عمداً org1..org8 مانده‌اند: کل زنجیره راه‌اندازی اثبات‌شده
# (CA دو سطحی، گواهی TLS، consenter های Raft، مسیرهای crypto-config)
# به این نام‌ها گره خورده و تغییرشان یعنی عیب‌یابی همه‌ی آن مسیر از نو.
# نام فارسی فقط لایه نمایش است — در API و داشبورد از همین جدول می‌آید.
# ---------------------------------------------------------------------------
declare -A ORG_TITLE=(
  [org1MSP]="شهرداری مرکزی — معاونت شهرسازی و معماری"
  [org2MSP]="مناطق یازده‌گانه شهرداری"
  [org3MSP]="سازمان نظام مهندسی ساختمان استان فارس"
  [org4MSP]="مالکان و دفاتر پیشخوان خدمات"
  [org5MSP]="معاونت مالی و اقتصادی و بانک عامل"
  [org6MSP]="کمیسیون ماده ۵ و ماده ۱۰۰ و شورای شهر"
  [org7MSP]="دستگاه‌های استعلام‌شونده"
  [org8MSP]="حوزه بازرسی، حسابرسی و شفافیت"
)

declare -A ORG_ROLE=(
  [org1MSP]="REGULATOR"
  [org2MSP]="DISTRICT"
  [org3MSP]="ENGINEER"
  [org4MSP]="CITIZEN"
  [org5MSP]="FINANCE"
  [org6MSP]="COMMISSION"
  [org7MSP]="UTILITY"
  [org8MSP]="AUDITOR"
)

